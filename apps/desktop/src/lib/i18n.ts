export type Key = keyof typeof en;

const [locale, setLocaleSignal] = createSignal<Locale>("en");

export function setLocale(l: Locale) {
  setLocaleSignal(l);
  document.documentElement.lang = l;
}

export function currentLocale(): Locale {
  return locale();
}

/** Translates a key, substituting `{name}` placeholders. Reactive under Solid. */
export function t(key: Key, vars?: Record<string, string | number>): string {
  // Reading the signal keeps callers reactive for the day a second table
  // arrives, without pretending one exists now.
  locale();
  let s = en[key] || key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

